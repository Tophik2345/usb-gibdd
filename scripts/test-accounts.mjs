import assert from 'node:assert/strict';
export async function checkAccounts({db,asUser,rpc,denied,A,B,C,base,checks}) {
  const D='a4444444-4444-4444-8444-444444444444', E='a5555555-5555-4555-8555-555555555555';
  const accounts=async payload=>(await db.query('select public.knowledge_accounts($1::jsonb) data',[JSON.stringify(payload)])).rows[0].data;
  const signup=async login=>(await db.query('select public.knowledge_signup_check($1::jsonb) data',[JSON.stringify({login})])).rows[0].data;
  await db.exec('reset role');
  await db.query("insert into auth.users(id,email,raw_user_meta_data) values ($1,'deletable@example.test','{\"login\":\"Удаляемый сотрудник\"}'),($2,'author@example.test','{\"login\":\"Автор с тестом\"}')",[D,E]);
  await db.query("insert into knowledge_private.test_creators(user_id,role) values ($1,'owner'),($2,'deputy'),($3,'author') on conflict(user_id) do update set role=excluded.role",[A,C,E]);
  await db.exec('create table auth.sessions(id uuid primary key,user_id uuid references auth.users(id) on delete cascade);create schema storage;create table storage.objects(owner_id text);');
  await db.query('insert into auth.sessions values(gen_random_uuid(),$1)',[D]);
  await asUser(null,'anon'); await denied(()=>accounts({action:'list'}),'42501');
  const occupied=await signup('  EXISTING   USER  '); assert.deepEqual(occupied,{available:false});
  assert.deepEqual(await signup('Новый логин'),{available:true});
  await denied(()=>signup(' '),'PT400');
  for(let i=0;i<119;i++) await signup('Новый логин');
  assert.deepEqual(await signup('Новый логин'),{limited:true});
  checks.push('Public signup availability normalizes names, exposes only a boolean and applies an independent limit');
  await asUser(D); await denied(()=>accounts({action:'list'}),'PT403');
  await db.query("select set_config('request.jwt.claims',$1,false)",[JSON.stringify({sub:D,app_metadata:{role:'owner'},user_metadata:{role:'owner'}})]);
  await denied(()=>accounts({action:'delete',userId:B,role:'owner'}),'PT403');
  await asUser(C);await denied(()=>accounts({action:'list'}),'PT403');
  await asUser(E);await denied(()=>accounts({action:'list'}),'PT403');
  await denied(()=>db.query("select knowledge_private.workspace_before_accounts('{}')"),'42501');
  await denied(()=>db.query("select knowledge_private.require_active_account(false)"),'42501');
  checks.push('Account listing/actions deny guests, employees, deputies and authors, including forged metadata and direct old RPC calls');
  await asUser(A);
  let list=await accounts({action:'list',search:'DELETABLE@'});assert.equal(list.total,1);assert.equal(list.accounts[0].userId,D);assert.equal(list.accounts[0].protected,false);
  assert.deepEqual(Object.keys(list.accounts[0]).sort(),['authoredTests','blocked','confirmed','createdAt','email','login','protected','results','role','userId'].sort());
  await denied(()=>accounts({action:'list',page:-1}),'PT400');
  await denied(()=>accounts({action:'list',search:'x'.repeat(101)}),'PT400');
  for(const target of [A,C]) for(const action of ['block','unblock','delete']) await denied(()=>accounts({action,userId:target}),'PT403');
  await denied(()=>accounts({action:'delete',userId:'bad-id'}),'PT400');
  await denied(()=>accounts({action:'delete',userId:'66666666-6666-4666-8666-666666666666'}),'PT404');
  checks.push('Owner-only search validates input; stable UUID actions protect the current owner and deputy');
  await asUser(E);const test=await rpc({...base,title:'Тест защищён от удаления автора'});
  await asUser(A);await denied(()=>accounts({action:'delete',userId:E}),'PT409');
  await asUser(D);const attempt=await rpc({action:'start',testId:test.id,employeeName:'Удаляемый сотрудник'});
  await asUser(A);await accounts({action:'block',userId:D});
  list=await accounts({action:'list',search:'deletable@'});assert.equal(list.accounts[0].blocked,true);assert.equal(list.accounts[0].results,1);
  await asUser(D);await denied(()=>rpc({}),'PT403');
  for(const name of ['knowledge_portal','knowledge_department','knowledge_training']) await denied(()=>db.query(`select public.${name}('{}')`),'PT403');
  await asUser(null,'anon');await db.query("select public.knowledge_portal('{\"op\":\"announcements\"}')");
  await db.exec('reset role');assert.equal((await db.query('select count(*)::int n from auth.sessions where user_id=$1',[D])).rows[0].n,0);
  assert.equal((await db.query('select count(*)::int n from knowledge_private.attempts where id=$1',[attempt.id])).rows[0].n,1);
  await asUser(A);await accounts({action:'unblock',userId:D});
  await asUser(D);assert((await rpc({})).attempts.some(a=>a.id===attempt.id));
  checks.push('Blocking revokes sessions and rejects old JWTs at every protected RPC; unblocking preserves personal results and public guest content');
  await db.exec('reset role');await db.query('insert into storage.objects values($1)',[D]);
  await asUser(A);await denied(()=>accounts({action:'delete',userId:D}),'PT409');
  await db.exec('reset role');await db.query('delete from storage.objects where owner_id=$1',[D]);
  await asUser(A);await accounts({action:'delete',userId:D});
  assert.equal((await accounts({action:'list',search:'deletable@'})).total,0);
  await denied(()=>accounts({action:'delete',userId:D}),'PT404');
  await asUser(D);await denied(()=>rpc({}),'PT401');
  await db.exec('reset role');
  assert.equal((await db.query('select count(*)::int n from knowledge_private.attempts where id=$1',[attempt.id])).rows[0].n,0);
  assert.equal((await db.query('select count(*)::int n from knowledge_private.tests where id=$1',[test.id])).rows[0].n,1);
  assert.equal((await db.query('select count(*)::int n from auth.users where id in ($1,$2,$3)',[A,C,E])).rows[0].n,3);
  const events=(await db.query("select operation from knowledge_private.management_events where area='accounts' and target_id=$1 order by id",[D])).rows.map(r=>r.operation);
  assert.deepEqual(events,['block','unblock','delete']);
  checks.push('Deletion protects authored tests and storage, cascades only target personal data, denies stale deleted identities and records owner actions');
  await asUser(A);await accounts({action:'block',userId:E});
  await asUser(E);await denied(()=>rpc({}),'PT403');
  await asUser(A);await accounts({action:'unblock',userId:E});
  await db.exec('reset role');await db.query('update auth.users set email_confirmed_at=null where id=$1',[A]);
  await asUser(A);await denied(()=>accounts({action:'list'}),'PT403');
  await db.exec('reset role');await db.query('update auth.users set email_confirmed_at=now() where id=$1',[A]);
  checks.push('Authors with tests can be blocked without losing their tests; an unconfirmed owner cannot administer accounts');
}
