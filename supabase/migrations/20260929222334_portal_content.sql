create function knowledge_private.portal(payload jsonb default '{}'::jsonb)
returns jsonb language plpgsql security definer set search_path='' as $$
declare
  v_uid uuid := auth.uid(); v_op text; v_role text; v_id uuid;
  v_document text; v_article text; v_title text; v_body text; v_kind text;
  v_url text; v_description text; v_category text; v_position integer;
  v_published boolean; v_pinned boolean; v_event timestamptz; v_version integer;
  v_announcement knowledge_private.announcements; v_link knowledge_private.useful_links;
begin
  if jsonb_typeof(payload) is distinct from 'object' or octet_length(payload::text)>40000 then
    raise exception using errcode='PT400',message='Некорректные данные.';
  end if;
  v_op:=coalesce(payload->>'action',payload->>'op','announcements');
  -- Only these two reads are public, and their queries exclude drafts.
  if v_op not in ('announcements','links') then
    if v_uid is null or not exists(select 1 from auth.users where id=v_uid and email_confirmed_at is not null) then
      raise exception using errcode='PT401',message='Войдите в аккаунт с подтверждённой почтой.';
    end if;
    if v_op not in ('bookmarks','setBookmark') then
      select role into v_role from knowledge_private.test_creators where user_id=v_uid for share;
      if v_role is null or v_role not in ('owner','deputy') then
        raise exception using errcode='PT403',message='Объявлениями и ссылками управляют владелец и заместитель.';
      end if;
    end if;
  end if;

  if v_op='setBookmark' then
    v_document:=knowledge_private.text_field(payload->'document','Документ',1,40);
    v_article:=knowledge_private.text_field(payload->'article','Статья',1,40);
    if jsonb_typeof(payload->'saved') is distinct from 'boolean' then
      raise exception using errcode='PT400',message='Укажите действие с избранным.';
    end if;
    if not exists(select 1 from knowledge_private.law_article_refs where document_id=v_document and article_id=v_article) then
      raise exception using errcode='PT404',message='Статья не найдена.';
    end if;
    if (payload->>'saved')::boolean then
      insert into knowledge_private.law_bookmarks(user_id,document_id,article_id) values(v_uid,v_document,v_article) on conflict do nothing;
    else
      delete from knowledge_private.law_bookmarks where user_id=v_uid and document_id=v_document and article_id=v_article;
    end if;
  end if;
  if v_op in ('bookmarks','setBookmark') then
    return jsonb_build_object('bookmarks',coalesce((select jsonb_agg(jsonb_build_object('document',document_id,'article',article_id) order by created_at desc,document_id,article_id) from knowledge_private.law_bookmarks where user_id=v_uid),'[]'::jsonb));
  end if;

  if v_op='saveAnnouncement' then
    v_title:=knowledge_private.text_field(payload->'title','Заголовок',3,140);
    v_body:=knowledge_private.text_field(payload->'body','Текст',1,6000);
    v_kind:=knowledge_private.text_field(payload->'kind','Тип объявления',1,20);
    if v_kind not in ('news','rules','attestation') then raise exception using errcode='PT400',message='Неизвестный тип объявления.'; end if;
    if jsonb_typeof(payload->'published') is distinct from 'boolean' or jsonb_typeof(payload->'pinned') is distinct from 'boolean' then
      raise exception using errcode='PT400',message='Укажите состояние публикации.';
    end if;
    v_published:=(payload->>'published')::boolean; v_pinned:=(payload->>'pinned')::boolean;
    v_event:=nullif(payload->>'eventAt','')::timestamptz;
    if v_event is not null and (not isfinite(v_event) or v_event<'2000-01-01'::timestamptz or v_event>'2200-01-01'::timestamptz) then
      raise exception using errcode='PT400',message='Проверьте дату события.';
    end if;
    v_id:=nullif(payload->>'id','')::uuid;
    if v_id is null then
      insert into knowledge_private.announcements(title,body,kind,event_at,pinned,published,published_at)
      values(v_title,v_body,v_kind,v_event,v_pinned,v_published,case when v_published then now() end) returning * into v_announcement;
    else
      v_version:=(payload->>'version')::integer;
      update knowledge_private.announcements set title=v_title,body=v_body,kind=v_kind,event_at=v_event,pinned=v_pinned,published=v_published,
        published_at=case when v_published then coalesce(published_at,now()) else published_at end,updated_at=now(),version=version+1
        where id=v_id and version=v_version returning * into v_announcement;
      if not found then raise exception using errcode='PT409',message='Объявление уже изменено. Обновите список и откройте его заново.'; end if;
    end if;
    return jsonb_build_object('id',v_announcement.id,'version',v_announcement.version);
  end if;
  if v_op in ('announcements','manageAnnouncements') then
    return jsonb_build_object('announcements',coalesce((select jsonb_agg(jsonb_build_object(
      'id',id,'title',title,'body',body,'kind',kind,'eventAt',event_at,'pinned',pinned,'published',published,
      'publishedAt',published_at,'updatedAt',updated_at,'version',version) order by pinned desc,coalesce(published_at,updated_at) desc,id)
      from knowledge_private.announcements where published or v_op='manageAnnouncements'),'[]'::jsonb));
  end if;

  if v_op='saveLink' then
    v_title:=knowledge_private.text_field(payload->'title','Название',3,120);
    v_description:=knowledge_private.text_field(coalesce(payload->'description','""'::jsonb),'Описание',0,300);
    v_url:=knowledge_private.text_field(payload->'url','Адрес',8,1500);
    if v_url !~ '^https://[A-Za-z0-9.-]+\.[A-Za-z]{2,}(:[0-9]{1,5})?([/?#][^[:space:]<>]*)?$' or (regexp_match(v_url,'^https://[^/?#]+:([0-9]+)'))[1]::integer not between 1 and 65535 then
      raise exception using errcode='PT400',message='Укажите полный адрес HTTPS без логина и пароля в ссылке.';
    end if;
    v_category:=knowledge_private.text_field(payload->'category','Раздел',1,20);
    if v_category not in ('forum','appeals','reports','contact') then raise exception using errcode='PT400',message='Неизвестный раздел ссылок.'; end if;
    if jsonb_typeof(payload->'published') is distinct from 'boolean' then raise exception using errcode='PT400',message='Укажите состояние публикации.'; end if;
    v_published:=(payload->>'published')::boolean;
    if coalesce(payload->>'position','') !~ '^[0-9]{1,4}$' then raise exception using errcode='PT400',message='Порядок: число от 0 до 1000.'; end if;
    v_position:=(payload->>'position')::integer;
    if v_position>1000 then raise exception using errcode='PT400',message='Порядок: число от 0 до 1000.'; end if;
    v_id:=nullif(payload->>'id','')::uuid;
    if v_id is null then
      insert into knowledge_private.useful_links(title,description,url,category,position,published)
      values(v_title,v_description,v_url,v_category,v_position,v_published) returning * into v_link;
    else
      v_version:=(payload->>'version')::integer;
      update knowledge_private.useful_links set title=v_title,description=v_description,url=v_url,category=v_category,position=v_position,
        published=v_published,updated_at=now(),version=version+1 where id=v_id and version=v_version returning * into v_link;
      if not found then raise exception using errcode='PT409',message='Ссылка уже изменена. Обновите список и откройте её заново.'; end if;
    end if;
    return jsonb_build_object('id',v_link.id,'version',v_link.version);
  end if;
  if v_op in ('links','manageLinks') then
    return jsonb_build_object('links',coalesce((select jsonb_agg(jsonb_build_object(
      'id',id,'title',title,'description',description,'url',url,'category',category,'position',position,'published',published,'version',version)
      order by position,title,id) from knowledge_private.useful_links where published or v_op='manageLinks'),'[]'::jsonb));
  end if;
  raise exception using errcode='PT400',message='Неизвестная операция.';
exception when invalid_text_representation or invalid_datetime_format or datetime_field_overflow or numeric_value_out_of_range then
  raise exception using errcode='PT400',message='Проверьте данные формы.';
end;
$$;
