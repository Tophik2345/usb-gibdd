-- Public content is explicitly published; personal bookmarks stay behind auth.uid().
create table knowledge_private.law_article_refs (
  document_id text not null,
  article_id text not null,
  primary key(document_id,article_id)
);
create table knowledge_private.law_bookmarks (
  user_id uuid not null references auth.users(id) on delete cascade,
  document_id text not null,
  article_id text not null,
  created_at timestamptz not null default now(),
  primary key(user_id,document_id,article_id),
  foreign key(document_id,article_id) references knowledge_private.law_article_refs(document_id,article_id) on delete cascade
);
create index law_bookmarks_article on knowledge_private.law_bookmarks(document_id,article_id);
create table knowledge_private.announcements (
  id uuid primary key default gen_random_uuid(),
  title text not null check(char_length(title) between 3 and 140),
  body text not null check(char_length(body) between 1 and 6000),
  kind text not null check(kind in ('news','rules','attestation')),
  event_at timestamptz,
  pinned boolean not null default false,
  published boolean not null default false,
  published_at timestamptz,
  updated_at timestamptz not null default now(),
  version integer not null default 1,
  check(not published or published_at is not null)
);
create index announcements_feed on knowledge_private.announcements(pinned desc,published_at desc) where published;
create table knowledge_private.useful_links (
  id uuid primary key default gen_random_uuid(),
  title text not null check(char_length(title) between 3 and 120),
  description text not null default '' check(char_length(description)<=300),
  url text not null check(char_length(url)<=1500 and url ~ '^https://[A-Za-z0-9.-]+\.[A-Za-z]{2,}(:[0-9]{1,5})?([/?#][^[:space:]<>]*)?$'),
  category text not null check(category in ('forum','appeals','reports','contact')),
  position integer not null default 0 check(position between 0 and 1000),
  published boolean not null default true,
  updated_at timestamptz not null default now(),
  version integer not null default 1
);
alter table knowledge_private.law_article_refs enable row level security;
alter table knowledge_private.law_bookmarks enable row level security;
alter table knowledge_private.announcements enable row level security;
alter table knowledge_private.useful_links enable row level security;
revoke all on knowledge_private.law_article_refs,knowledge_private.law_bookmarks,knowledge_private.announcements,knowledge_private.useful_links from public,anon,authenticated;

